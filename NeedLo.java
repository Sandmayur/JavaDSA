public class NeedLo {
    public static void main(String[] args) {
System.out.print("For Loop: ");
for (int i = 1; i <= 5; i++) {
    if (i > 1) {
        System.out.print(" ");
    }
    System.out.print(i);
}

System.out.print(" While Loop: ");
int j = 1;
while (j <= 5) {
    if (j > 1) {
        System.out.print(" ");
    }
    System.out.print(j);
    j++;
}

System.out.print(" Do-While Loop: ");
int c = 1;
do {
    if (c > 1) {
        System.out.print(" ");
    }
    System.out.print(c);
    c++;
} while (c <= 5);
    }
}
























